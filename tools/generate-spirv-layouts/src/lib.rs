use serde::Deserialize;
use serde_json::Value;
use std::{collections::BTreeMap, path::Path};

const PURE_CLASSES: &[&str] = &[
    "Type-Declaration",
    "Constant-Creation",
    "Composite",
    "Conversion",
    "Arithmetic",
    "Bit",
    "Logical",
    "Derivative",
];

#[derive(Deserialize)]
struct Grammar {
    operand_kinds: Vec<OperandKind>,
    instructions: Vec<Instruction>,
}

#[derive(Deserialize)]
struct OperandKind {
    kind: String,
    #[serde(default)]
    enumerants: Vec<Enumerant>,
}

#[derive(Deserialize)]
struct Enumerant {
    #[serde(default)]
    parameters: Vec<Value>,
}

#[derive(Deserialize)]
struct Instruction {
    opname: String,
    class: String,
    opcode: u32,
    #[serde(default)]
    operands: Vec<Operand>,
}

#[derive(Deserialize)]
struct Operand {
    kind: String,
    quantifier: Option<String>,
}

struct Layout {
    result: Option<usize>,
    id_mask: u128,
    tail: Option<usize>,
    minimum: usize,
    maximum: Option<usize>,
    pure: bool,
}

enum InstructionState {
    Omitted,
    Generated(Layout),
}

pub fn generate(raw: &str, grammar_path: &Path) -> Result<String, String> {
    let grammar: Grammar =
        serde_json::from_str(raw).map_err(|error| format!("parse grammar: {error}"))?;
    let complex_kinds = grammar
        .operand_kinds
        .iter()
        .filter(|kind| {
            kind.enumerants
                .iter()
                .any(|enumerant| !enumerant.parameters.is_empty())
        })
        .map(|kind| kind.kind.as_str())
        .collect::<Vec<_>>();
    let mut lines = vec![
        "// Generated by tools/generate-spirv-layouts. Do not edit.".to_owned(),
        "// Khronos SPIR-V grammar. Copyright (c) 2014-2024 The Khronos Group Inc.".to_owned(),
        "// SPDX-License-Identifier: MIT".to_owned(),
        "use super::Layout;".to_owned(),
        "use crate::spirv::Op;".to_owned(),
        String::new(),
        "static TABLE: [Option<Layout>; 401] = {".to_owned(),
        "    let mut table = [None; 401];".to_owned(),
    ];

    for instruction in &grammar.instructions {
        let InstructionState::Generated(layout) = classify(instruction, &complex_kinds) else {
            continue;
        };
        let marker = format!("\"opname\" : \"{}\"", instruction.opname);
        let byte = raw
            .find(&marker)
            .ok_or_else(|| format!("cannot locate {} in grammar text", instruction.opname))?;
        let line = raw[..byte].bytes().filter(|byte| *byte == b'\n').count() + 1;
        lines.push(format!(
            "    // {}: {}:{}",
            instruction.opname,
            grammar_path.display(),
            line
        ));
        lines.push(format!(
            "    table[{}] = Some(Layout::new({}, {}, {}, {}, {}, {}));",
            instruction.opcode,
            option(layout.result),
            layout.id_mask,
            option(layout.tail),
            layout.minimum,
            option(layout.maximum),
            layout.pure
        ));
    }

    lines.extend([
        "    table".to_owned(),
        "};".to_owned(),
        String::new(),
        "pub(super) fn layout(op: Op) -> Option<Layout> {".to_owned(),
        "    TABLE.get(usize::from(op)).copied().flatten()".to_owned(),
        "}".to_owned(),
    ]);
    Ok(lines.join("\n") + "\n")
}

pub fn check(generated: &str, checked_in: &str) -> Result<(), String> {
    if generated == checked_in {
        Ok(())
    } else {
        Err("generated layout table differs from the checked-in file".to_owned())
    }
}

pub fn check_opcodes(raw: &str, source: &str) -> Result<(), String> {
    let grammar: Grammar =
        serde_json::from_str(raw).map_err(|error| format!("parse grammar: {error}"))?;
    let expected = grammar
        .instructions
        .iter()
        .map(|instruction| {
            (
                instruction
                    .opname
                    .strip_prefix("Op")
                    .unwrap_or(&instruction.opname),
                instruction.opcode,
            )
        })
        .collect::<BTreeMap<_, _>>();
    let declarations = source
        .split_once("opcodes! {")
        .and_then(|(_, tail)| tail.split_once('\n'))
        .map(|(_, body)| body)
        .ok_or_else(|| "cannot locate opcodes! declaration".to_owned())?;
    let mut checked = 0;
    for line in declarations.lines() {
        let line = line.trim();
        if line == "}" {
            break;
        }
        let Some((name, number)) = line
            .strip_suffix(',')
            .and_then(|line| line.split_once(" = "))
        else {
            return Err(format!("cannot parse opcode declaration: {line}"));
        };
        let number = number
            .parse::<u32>()
            .map_err(|error| format!("parse opcode {name}: {error}"))?;
        match expected.get(name) {
            Some(expected) if *expected == number => checked += 1,
            Some(expected) => {
                return Err(format!(
                    "Op{name} is {number}, but the grammar assigns {expected}"
                ));
            }
            None => return Err(format!("Op{name} does not exist in the grammar")),
        }
    }
    if checked == 0 {
        Err("opcodes! declaration is empty".to_owned())
    } else {
        Ok(())
    }
}

fn classify(instruction: &Instruction, complex_kinds: &[&str]) -> InstructionState {
    if instruction.opcode > 400 || is_special(instruction.opcode) {
        return InstructionState::Omitted;
    }
    let mut layout = Layout {
        result: None,
        id_mask: 0,
        tail: None,
        minimum: 0,
        maximum: Some(0),
        pure: false,
    };
    for (index, operand) in instruction.operands.iter().enumerate() {
        if complex_kinds.contains(&operand.kind.as_str())
            || operand.kind == "LiteralString"
            || operand.kind.starts_with("Pair")
        {
            return InstructionState::Omitted;
        }
        if operand.kind == "IdResult" {
            layout.result = Some(index);
        } else if operand.kind.starts_with("Id") {
            if operand.quantifier.as_deref() == Some("*") {
                layout.tail = Some(index);
            } else {
                layout.id_mask |= 1u128 << index;
            }
        }
        if operand.quantifier.is_none() {
            layout.minimum += 1;
        }
        if operand.quantifier.as_deref() == Some("*")
            || operand.kind == "LiteralContextDependentNumber"
        {
            layout.maximum = None;
        } else if let Some(maximum) = &mut layout.maximum {
            *maximum += 1;
        }
    }
    layout.pure = (PURE_CLASSES.contains(&instruction.class.as_str()) && layout.result.is_some())
        || instruction.opcode == 12;
    InstructionState::Generated(layout)
}

fn is_special(opcode: u32) -> bool {
    matches!(
        opcode,
        15 | 16 | 61 | 62 | 71 | 72 | 87..=99 | 245 | 246 | 251
    )
}

fn option(value: Option<usize>) -> String {
    value.map_or_else(|| "None".to_owned(), |value| format!("Some({value})"))
}

#[cfg(test)]
mod tests {
    use super::{check, check_opcodes, generate};
    use std::path::Path;

    #[test]
    fn generates_supported_layouts_and_omits_unsupported_states() {
        let raw = r#"{
  "operand_kinds" : [
    { "kind" : "Simple", "enumerants" : [] },
    { "kind" : "Complex", "enumerants" : [
      { "enumerant" : "WithParameter", "parameters" : [{ "kind" : "IdRef" }] }
    ] }
  ],
  "instructions" : [
    { "opname" : "OpPure", "class" : "Arithmetic", "opcode" : 5,
      "operands" : [
        { "kind" : "IdResult" },
        { "kind" : "IdRef" },
        { "kind" : "IdRef", "quantifier" : "*" }
      ] },
    { "opname" : "OpOptional", "class" : "Miscellaneous", "opcode" : 6,
      "operands" : [
        { "kind" : "LiteralInteger" },
        { "kind" : "IdRef", "quantifier" : "?" }
      ] },
    { "opname" : "OpContext", "class" : "Miscellaneous", "opcode" : 9,
      "operands" : [{ "kind" : "LiteralContextDependentNumber" }] },
    { "opname" : "OpExtInst", "class" : "Miscellaneous", "opcode" : 12 },
    { "opname" : "OpSpecial", "class" : "Arithmetic", "opcode" : 15 },
    { "opname" : "OpTooLarge", "class" : "Arithmetic", "opcode" : 401 },
    { "opname" : "OpComplex", "class" : "Arithmetic", "opcode" : 18,
      "operands" : [{ "kind" : "Complex" }] },
    { "opname" : "OpString", "class" : "Arithmetic", "opcode" : 19,
      "operands" : [{ "kind" : "LiteralString" }] },
    { "opname" : "OpPair", "class" : "Arithmetic", "opcode" : 20,
      "operands" : [{ "kind" : "PairLiteralIntegerIdRef" }] }
  ]
}"#;

        let expected = r#"// Generated by tools/generate-spirv-layouts. Do not edit.
// Khronos SPIR-V grammar. Copyright (c) 2014-2024 The Khronos Group Inc.
// SPDX-License-Identifier: MIT
use super::Layout;
use crate::spirv::Op;

static TABLE: [Option<Layout>; 401] = {
    let mut table = [None; 401];
    // OpPure: /fixture/spirv.core.grammar.json:9
    table[5] = Some(Layout::new(Some(0), 2, Some(2), 2, None, true));
    // OpOptional: /fixture/spirv.core.grammar.json:15
    table[6] = Some(Layout::new(None, 2, None, 1, Some(2), false));
    // OpContext: /fixture/spirv.core.grammar.json:20
    table[9] = Some(Layout::new(None, 0, None, 1, None, false));
    // OpExtInst: /fixture/spirv.core.grammar.json:22
    table[12] = Some(Layout::new(None, 0, None, 0, Some(0), true));
    table
};

pub(super) fn layout(op: Op) -> Option<Layout> {
    TABLE.get(usize::from(op)).copied().flatten()
}
"#;

        assert_eq!(
            generate(raw, Path::new("/fixture/spirv.core.grammar.json")).unwrap(),
            expected
        );
    }

    #[test]
    fn check_accepts_only_the_exact_generated_bytes() {
        assert_eq!(check("same\n", "same\n"), Ok(()));
        assert_eq!(
            check("generated\n", "checked in\n"),
            Err("generated layout table differs from the checked-in file".to_owned())
        );
    }

    #[test]
    fn checks_named_opcode_numbers_against_the_grammar() {
        let grammar = r#"{
            "operand_kinds": [],
            "instructions": [
                {"opname": "OpNop", "class": "Miscellaneous", "opcode": 0},
                {"opname": "OpTypeInt", "class": "Type-Declaration", "opcode": 21}
            ]
        }"#;
        check_opcodes(grammar, "opcodes! {\n    Nop = 0,\n    TypeInt = 21,\n}\n").unwrap();
        assert!(check_opcodes(grammar, "opcodes! {\n    Nop = 1,\n}\n")
            .unwrap_err()
            .contains("grammar assigns 0"));
    }
}
